"""List the library API surface used by the project units (from the Ghidra .s export).

Usage: python tools/compat_surface.py build/decomp-1.1 symbols/units-1.1.json build/project-classes-1.1.txt > symbols/compat-surface.md
"""
import collections
import glob
import json
import os
import re
import sys


def main():
    decomp, units_json = sys.argv[1:3]
    units = json.load(open(units_json))['units']
    project = {u['name'] or 'Unit%d' % u['init_order'] for u in units if not u['library']}
    if len(sys.argv) > 3:   # project class names (build/project-classes-<ver>.txt)
        project |= {l.strip() for l in open(sys.argv[3]) if l.strip()}
    calls = collections.defaultdict(collections.Counter)
    data = collections.defaultdict(collections.Counter)
    for path in sorted(glob.glob(os.path.join(decomp, '*.s'))):
        unit = os.path.splitext(os.path.basename(path))[0]
        for line in open(path):
            m = re.search(r'\b(CALL|JMP)\s+([A-Za-z_@][\w.@:]*)', line)
            if m:
                name = m.group(2)
                owner = name.split('.')[0]
                if (name.startswith(('FUN_', 'LAB_', 'SUB_', 'switchD', 'caseD')) or owner in project
                        or name in ('dword', 'word', 'byte')):
                    continue
                calls[name][unit] += 1
            for g in re.findall(r'\[(PTR_[A-Za-z]\w*)\]', line):
                if not re.match(r'PTR_(DAT|LAB|FUN|VMT_T\w+_00)', g):
                    data[g][unit] += 1
            for v in re.findall(r'(VMT_T\w+?)_[0-9a-f]{8}', line):
                data[v][unit] += 1
    print('# Library surface used by the project units\n')
    print('Generated by `tools/compat_surface.py` from the Ghidra export. Counts are call sites.\n')
    print('## Routines\n')
    for name in sorted(calls, key=lambda n: (n.split('.')[0].lstrip('@').lower(), n)):
        units = ', '.join('%s×%d' % kv for kv in sorted(calls[name].items()))
        print('- `%s` — %s' % (name, units))
    print('\n## Globals and class references\n')
    for name in sorted(data):
        units = ', '.join('%s×%d' % kv for kv in sorted(data[name].items()))
        print('- `%s` — %s' % (name, units))


if __name__ == '__main__':
    main()
